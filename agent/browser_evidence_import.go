const (
	playwrightImageMaxBytes = 25 << 20
	playwrightTraceMaxBytes = 32 << 20
	playwrightMaxDimension  = 32768
	playwrightMaxPixels     = 100_000_000
)

type browserEvidenceImportInput struct {
	ReceiptPath string `json:"receipt_path"`
}

// IngestBrowserEvidenceTool exposes the task-bound code-owned importer to the
// server's retest host-tool adapter. WorkerTools uses the same handler directly.
func (t *ToolSet) IngestBrowserEvidenceTool() actool.CoreTool { return t.ingestBrowserEvidence() }

// ingestBrowserEvidence imports original Playwright image/trace bytes from the
// current run directory into ARTEX's server-owned evidence store. The model
// cannot manufacture a verified artifact by printing an artifact-shaped JSON
// object: capture.go accepts the envelope only when this exact tool produced the
// audited tool_result, and the finding API re-hashes the stored bytes.
func (t *ToolSet) ingestBrowserEvidence() actool.CoreTool {
	const name = "ingest_browser_evidence"
	return actool.Build(actool.Spec{
		Name:        name,
		Description: "Import original Playwright browser evidence from this run's working directory using only a signed receipt returned by capture_playwright_evidence. A valid PNG/JPEG alone is not trusted: files created, copied, reconstructed, or generated by the model/shell have no ARTEX capture receipt and are refused. The receipt binds task/run, source URL, timestamp, capture tool call, screenshot hash, and optional JSON/HAR trace hash. Paths outside the run directory, symlinks, hard links, malformed files, receipt tampering/replay, hash mismatches, userinfo URLs, and oversized files are refused. Returns a code-owned artifact envelope whose exact bytes are re-hashed before the Finding UI marks them verified.",
		Schema: obj(map[string]any{
			"receipt_path": str("signed .receipt.json path returned by capture_playwright_evidence, relative to this run directory"),
		}, "receipt_path"),
		Permissions: func(context.Context, json.RawMessage, acperm.Context) acperm.Decision { return acperm.Allowed() },
		Run: func(ctx context.Context, in json.RawMessage, tc *actool.ToolContext) (actool.Result, error) {
			return t.needExploration(name, func(_ context.Context, in json.RawMessage) (actool.Result, error) {
				return t.runBrowserEvidenceImport(in, tc)
			})(ctx, in)
		},
	})
}

func (t *ToolSet) runBrowserEvidenceImport(in json.RawMessage, tc *actool.ToolContext) (actool.Result, error) {
	if t.taskID <= 0 || strings.TrimSpace(t.workBase) == "" {
		return actool.Errorf("browser evidence import requires task context"), nil
	}
	var a browserEvidenceImportInput
	if err := json.Unmarshal(in, &a); err != nil {
		return actool.Errorf("invalid input: " + err.Error()), nil
	}
	if tc == nil || strings.TrimSpace(tc.WorkingDir) == "" || strings.TrimSpace(tc.ToolUseID) == "" {
		return actool.Errorf("browser evidence import requires the current run directory and audited tool call id"), nil
	}
	workingDir := tc.WorkingDir
	// Worker evidence must originate from that task's claimed intent directory,
	// never another task/run under the shared data root. Retesters use an
	// isolated conversation directory that the server adapter validates against
	// its server-owned conversation id before delegating here.
	if t.worker != "retester" && !browserEvidenceIntentDir(t.workBase, t.taskID, workingDir) {
		return actool.Errorf("browser evidence import requires the current task intent directory"), nil
	}
	a.ReceiptPath = strings.TrimSpace(a.ReceiptPath)
	if a.ReceiptPath == "" {
		return actool.Errorf("receipt_path from capture_playwright_evidence is required"), nil
	}
	receiptBytes, err := readConfinedEvidenceFile(t.workBase, workingDir, a.ReceiptPath, browserCaptureReceiptMax)
	if err != nil {
		return actool.Errorf("capture receipt: " + safeBrowserImportError(err)), nil
	}
	receipt, err := verifyBrowserCaptureReceipt(receiptBytes)
	if err != nil {
		return actool.Errorf(browserReceiptError(err)), nil
	}
	workspace, err := browserRunWorkspace(t.workBase, workingDir)
	if err != nil || receipt.Version != browserCaptureReceiptVersion || receipt.TaskID != t.taskID || receipt.Workspace != workspace ||
		receipt.CaptureTool != "artex_playwright_cli" || receipt.Browser != "chromium" || strings.TrimSpace(receipt.PlaywrightVersion) == "" ||
		strings.TrimSpace(receipt.CaptureToolUseID) == "" || strings.TrimSpace(receipt.ReceiptID) == "" {
		return actool.Errorf("capture receipt does not belong to this task/run or trusted capture helper"), nil
	}
	u, err := url.Parse(strings.TrimSpace(receipt.SourceURL))
	if err != nil || u.User != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Hostname() == "" {
		return actool.Errorf("capture receipt source URL is invalid"), nil
	}
	capturedAt, err := time.Parse(time.RFC3339Nano, strings.TrimSpace(receipt.CapturedAt))
	if err != nil || capturedAt.After(time.Now().UTC().Add(5*time.Minute)) {
		return actool.Errorf("capture receipt timestamp is invalid"), nil
	}
	if !validExpectedSHA256(receipt.ScreenshotSHA256) {
		return actool.Errorf("capture receipt screenshot hash is invalid"), nil
	}
	if receipt.TracePath == "" {
		if receipt.TraceSHA256 != "" || receipt.TraceFormat != "" {
			return actool.Errorf("capture receipt trace declaration is inconsistent"), nil
		}
	} else if !validExpectedSHA256(receipt.TraceSHA256) || (receipt.TraceFormat != "json" && receipt.TraceFormat != "har") {
		return actool.Errorf("capture receipt trace declaration is invalid"), nil
	}
	imageBytes, err := readConfinedEvidenceFile(t.workBase, workingDir, receipt.ScreenshotPath, playwrightImageMaxBytes)
	if err != nil {
		return actool.Errorf("screenshot: " + safeBrowserImportError(err)), nil
	}
	imageHash := sha256.Sum256(imageBytes)
	imageHashText := hex.EncodeToString(imageHash[:])
	if imageHashText != receipt.ScreenshotSHA256 {
		return actool.Errorf("screenshot SHA-256 mismatch"), nil
	}
	imageMIME, imageExt, err := validateBrowserImage(imageBytes)
	if err != nil {
		return actool.Errorf("screenshot: " + err.Error()), nil
	}

	cfg := taskEvidenceConfig(t.workBase, t.taskID)
	imageRef, err := persistImportedEvidence(cfg, "browser-playwright-", imageHashText, imageExt, imageBytes)
	if err != nil {
		return actool.Errorf("screenshot evidence could not be stored"), nil
	}
	artifacts := []EvidenceArtifact{{
		Ref:          imageRef,
		Kind:         "browser_screenshot",
		Label:        "Actual Playwright browser screenshot",
		MIMEType:     imageMIME,
		SHA256:       imageHashText,
		ByteSize:     int64(len(imageBytes)),
		CapturedAt:   capturedAt.UTC(),
		Tool:         "playwright",
		SourceURL:    u.String(),
		OriginalName: filepath.Base(receipt.ScreenshotPath),
		Sensitive:    true,
	}}
	var networkTrace map[string]any

	if receipt.TracePath != "" {
		traceBytes, readErr := readConfinedEvidenceFile(t.workBase, workingDir, receipt.TracePath, playwrightTraceMaxBytes)
		if readErr != nil {
			return actool.Errorf("trace: " + safeBrowserImportError(readErr)), nil
		}
		traceHash := sha256.Sum256(traceBytes)
		traceHashText := hex.EncodeToString(traceHash[:])
		if traceHashText != receipt.TraceSHA256 {
			return actool.Errorf("trace SHA-256 mismatch"), nil
		}
		if err := validateBrowserTrace(traceBytes, receipt.TraceFormat); err != nil {
			return actool.Errorf("trace: " + err.Error()), nil
		}
		traceRef, storeErr := persistImportedEvidence(cfg, "browser-playwright-trace-", traceHashText, ".json", traceBytes)
		if storeErr != nil {
			return actool.Errorf("trace evidence could not be stored"), nil
		}
		// Network traces can contain cookies or authorization headers and the
		// current Finding gallery renders every evidence_artifact as an image.
		// Keep the exact trace in the protected evidence store and declare its
		// ref/hash in the audited tool result, but do not add it to the image
		// artifacts array. A dedicated redacted-download UI can promote it later.
		networkTrace = map[string]any{
			"ref": traceRef, "kind": "browser_network_trace", "mime_type": "application/json",
			"sha256": traceHashText, "byte_size": len(traceBytes), "captured_at": capturedAt.UTC(),
			"tool": "playwright", "source_url": u.String(), "original_name": filepath.Base(receipt.TracePath),
			"trace_format": receipt.TraceFormat, "sensitive": true, "gallery_visible": false,
		}
	}

	out := map[string]any{
		"capture_tool": "playwright",
		"source_url":   u.String(),
		"captured_at":  capturedAt.UTC(),
		"artifacts":    artifacts,
		"capture_receipt": map[string]any{
			"receipt_id": receipt.ReceiptID, "receipt_sha256": browserReceiptHash(receiptBytes),
			"capture_tool": receipt.CaptureTool, "capture_tool_use_id": receipt.CaptureToolUseID,
			"browser": receipt.Browser, "playwright_version": receipt.PlaywrightVersion,
		},
	}
	if networkTrace != nil {
		out["network_trace"] = networkTrace
	}
	return jsonResult(out)
}

func browserEvidenceIntentDir(base string, taskID int64, dir string) bool {
	absBase, err := filepath.Abs(base)
	if err != nil {
		return false
	}
	absDir, err := filepath.Abs(dir)
	if err != nil {
		return false
	}
	taskRoot := filepath.Join(absBase, "tasks", strconv.FormatInt(taskID, 10))
	rel, err := filepath.Rel(taskRoot, absDir)
	if err != nil || !filepath.IsLocal(rel) || filepath.Dir(rel) != "." || !strings.HasPrefix(rel, "i") {
		return false
	}
	intentID, err := strconv.ParseInt(strings.TrimPrefix(rel, "i"), 10, 64)
	return err == nil && intentID > 0
}

func validExpectedSHA256(value string) bool {
	value = strings.TrimSpace(value)
	if len(value) != 64 || value != strings.ToLower(value) {
		return false
	}
	_, err := hex.DecodeString(value)
	return err == nil
}

func readConfinedEvidenceFile(base, workingDir, path string, capBytes int64) ([]byte, error) {
	f, err := openScanOutputInBase(base, workingDir, path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, capBytes+1))
	if err != nil {
		return nil, err
	}
	if len(data) == 0 {
		return nil, errors.New("file is empty")
	}
	if int64(len(data)) > capBytes {
		return nil, fmt.Errorf("file exceeds the %d byte cap", capBytes)
	}
	return data, nil
}

func validateBrowserImage(data []byte) (mime, ext string, err error) {
	contentType := ""
	if len(data) >= 8 && bytes.Equal(data[:8], []byte("\x89PNG\r\n\x1a\n")) {
		contentType = "image/png"
		ext = ".png"
	} else if len(data) >= 3 && data[0] == 0xff && data[1] == 0xd8 && data[2] == 0xff {
		contentType = "image/jpeg"
		ext = ".jpg"
	} else {
		return "", "", errors.New("only PNG or JPEG image content is accepted")
	}
	cfg, format, decodeErr := image.DecodeConfig(bytes.NewReader(data))
	if decodeErr != nil || (format != "png" && format != "jpeg") {
		return "", "", errors.New("image header is malformed")
	}
	if (format == "png") != (contentType == "image/png") {
		return "", "", errors.New("image signature and decoder format disagree")
	}
	if cfg.Width <= 0 || cfg.Height <= 0 || cfg.Width > playwrightMaxDimension || cfg.Height > playwrightMaxDimension || int64(cfg.Width)*int64(cfg.Height) > playwrightMaxPixels {
		return "", "", errors.New("image dimensions exceed the safety limit")
	}
	return contentType, ext, nil
}

func validateBrowserTrace(data []byte, format string) error {
	if !json.Valid(data) {
		return errors.New("network trace is not valid JSON")
	}
	if format != "har" {
		return nil
	}
	var root map[string]json.RawMessage
	if err := json.Unmarshal(data, &root); err != nil || len(root["log"]) == 0 {
		return errors.New("HAR must contain a log object")
	}
	var logObject map[string]json.RawMessage
	if err := json.Unmarshal(root["log"], &logObject); err != nil || len(logObject["entries"]) == 0 {
		return errors.New("HAR log must contain entries")
	}
	var entries []json.RawMessage
	if err := json.Unmarshal(logObject["entries"], &entries); err != nil {
		return errors.New("HAR log.entries must be an array")
	}
	return nil
}

func persistImportedEvidence(cfg evidenceCaptureConfig, prefix, digest, ext string, data []byte) (string, error) {
	if err := os.MkdirAll(cfg.Dir, 0o700); err != nil {
		return "", err
	}
	name := prefix + digest + ext
	dest := filepath.Join(cfg.Dir, name)
	if existing, err := os.ReadFile(dest); err == nil {
		if !bytes.Equal(existing, data) {
			return "", errors.New("existing evidence digest collision")
		}
		return filepath.ToSlash(filepath.Join(cfg.RefPrefix, name)), nil
	} else if !os.IsNotExist(err) {
		return "", err
	}
	tmp, err := os.CreateTemp(cfg.Dir, ".browser-import-*")
	if err != nil {
		return "", err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return "", err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return "", err
	}
	if err := tmp.Close(); err != nil {
		return "", err
	}
	if err := os.Rename(tmpName, dest); err != nil {
		return "", err
	}
	return filepath.ToSlash(filepath.Join(cfg.RefPrefix, name)), nil
}

func safeBrowserImportError(err error) string {
	if err == nil {
		return "file unavailable"
	}
	text := strings.ToLower(err.Error())
	switch {
	case strings.Contains(text, "symlink"):
		return "symlinks are not allowed"
	case strings.Contains(text, "hard link"):
		return "hard-linked files are not allowed"
	case strings.Contains(text, "not a regular"):
		return "path is not a regular file"
	case strings.Contains(text, "must not contain .."), strings.Contains(text, "outside"):
		return "path must stay inside the run directory"
	default:
		return "file unavailable or invalid"
	}
}
